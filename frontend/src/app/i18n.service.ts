// ── Service ───────────────────────────────────────────────────────────────────

@Injectable({ providedIn: 'root' })
export class I18nService {
  private readonly http = inject(HttpClient);
  /** False during SSR/prerender (no localStorage, no backend reachable).
   *  Gates browser-only init so SSG route extraction doesn't hang on the
   *  /api/config fetch. */
  private readonly isBrowser = isPlatformBrowser(inject(PLATFORM_ID));

  /** Reactive lang signal — components can read directly */
  readonly lang = signal<Lang>('uk');

  /**
   * Initialise language from the server config endpoint.
   * Called via APP_INITIALIZER so it resolves before any component renders.
   * Falls back to 'uk' on any error.
   */
  async init(): Promise<void> {
    // SSR / prerender: no localStorage, no backend reachable — keep the 'uk'
    // default and return immediately so SSG route extraction doesn't block on
    // the /api/config fetch (which would never resolve at build time).
    if (!this.isBrowser) return;
    // User's explicit preference always wins over the server default.
    // This lets them switch language once and have it persist across
    // page refreshes without needing a separate EN/FR deployment.
    try {
      const stored = localStorage.getItem('reflect.lang') as Lang | null;
      if (this.isSupported(stored)) {
        this.setLang(stored);
        return;
      }
    } catch { /* localStorage blocked (private browsing) — ignore */ }

    // No stored preference → fall back to server default (REFLECT_LANG).
    try {
      const cfg = await firstValueFrom(
        this.http.get<{ lang: string }>('/api/config'),
      );
      const fromServer = cfg?.lang as Lang | undefined;
      this.setLang(this.isSupported(fromServer) ? fromServer : 'uk');
    } catch {
      this.setLang('uk');
    }
  }

  /** Type-narrowing guard for the supported lang set. */
  private isSupported(l: string | null | undefined): l is Lang {
    return l === 'uk' || l === 'en' || l === 'fr';
  }

  /** Set active language and persist to localStorage for next visit */
  setLang(lang: Lang): void {
    this.lang.set(lang);
    try { localStorage.setItem('reflect.lang', lang); } catch {}
    // Set <html lang> for screen readers / SEO
    if (typeof document !== 'undefined') {
      document.documentElement.lang = lang;
    }
  }

  /**
   * Translate a key. Optional `vars` map substitutes `{var}` placeholders
   * — keeps tiny templates (1 var, no plurals) inline without a full
   * ICU library. Missing keys fall back to the UK string, then to the
   * raw key (fail-safe so a broken translation never blanks the UI).
   */
  t(key: string, vars?: Record<string, string | number | undefined>): string {
    const raw = T[this.lang()][key] ?? T['uk'][key] ?? key;
    if (!vars) return raw;
    return raw.replace(/\{(\w+)\}/g, (_, name: string) =>
      String(vars[name] ?? `{${name}}`),
    );
  }

  /** True when the app is running in English mode. Kept for back-compat
   *  with inline ternaries; new code should prefer `i18n.t('key')` so
   *  it works for all locales (uk/en/fr) without per-component edits. */
  get isEn(): boolean {
    return this.lang() === 'en';
  }

  /** True when the app is running in French mode. */
  get isFr(): boolean {
    return this.lang() === 'fr';
  }
}
